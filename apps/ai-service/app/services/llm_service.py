import asyncio
import logging
import time
from typing import Any, Generic, TypeVar, cast

import groq
import httpx
from langchain_core.exceptions import OutputParserException
from langchain_core.messages import BaseMessage, HumanMessage, SystemMessage
from langchain_groq import ChatGroq
from pydantic import BaseModel, Field, ValidationError
from tenacity import (
    AsyncRetrying,
    retry_if_exception_type,
    stop_after_attempt,
    wait_random_exponential,
)

from app.core.config import settings
from app.integrations.groq_client import (
    GroqAPIError,
    GroqAuthenticationError,
    GroqBadRequestError,
    GroqConfigurationError,
    GroqRateLimitError,
    GroqStructuredOutputError,
    GroqTimeoutError,
    groq_client,
)

logger = logging.getLogger("app.services.llm_service")


class LLMError(Exception):
    def __init__(self, message: str, original_error: Exception | None = None):
        super().__init__(message)
        self.original_error = original_error


class LLMAuthenticationError(LLMError):
    pass


class LLMBadRequestError(LLMError):
    pass


class LLMValidationError(LLMError):
    pass


class LLMRateLimitError(LLMError):
    pass


class LLMTimeoutError(LLMError):
    pass


class LLMModelError(LLMError):
    pass


class LLMUsage(BaseModel):
    input_tokens: int = Field(default=0, description="Tokens in user and system prompts")
    output_tokens: int = Field(default=0, description="Tokens generated by the model")
    total_tokens: int = Field(default=0, description="Total tokens consumed by the transaction")


T = TypeVar("T")
TStruct = TypeVar("TStruct", bound=BaseModel)


class LLMResponse(BaseModel, Generic[T]):
    content: T = Field(description="Generated string or validated Pydantic model instance")
    model: str = Field(description="Identifier of the model that served the request")
    latency_ms: float = Field(description="Round-trip request duration in milliseconds")
    usage: LLMUsage | None = Field(default=None, description="Token usage details")


class LLMService:

    def __init__(
        self,
        default_model: str | None = None,
        default_temperature: float | None = None,
        default_max_tokens: int | None = None,
        default_timeout: float | None = None,
        max_retries: int = 3,
    ):
        self.default_model = default_model or settings.GROQ_MODEL
        self.default_temperature = default_temperature if default_temperature is not None else settings.GROQ_TEMPERATURE
        self.default_max_tokens = default_max_tokens or settings.GROQ_MAX_TOKENS
        self.default_timeout = default_timeout or float(settings.GROQ_TIMEOUT)
        self.max_retries = max(1, max_retries)

    def _get_chat_model(
        self,
        model: str | None = None,
        temperature: float | None = None,
        max_tokens: int | None = None,
        timeout: float | None = None,
    ) -> ChatGroq:
        try:
            return groq_client.get_model(
                model=model or self.default_model,
                temperature=temperature if temperature is not None else self.default_temperature,
                max_tokens=max_tokens or self.default_max_tokens,
                timeout=timeout or self.default_timeout,
                max_retries=0,
            )
        except Exception as exc:
            raise self._map_exception(exc) from exc

    def _build_messages(
        self,
        prompt: str,
        system_prompt: str | None = None,
    ) -> list[BaseMessage]:
        messages: list[BaseMessage] = []
        if system_prompt and system_prompt.strip():
            messages.append(SystemMessage(content=system_prompt.strip()))
        messages.append(HumanMessage(content=prompt.strip()))
        return messages

    def _extract_usage(self, response: Any) -> LLMUsage | None:
        if hasattr(response, "usage_metadata") and response.usage_metadata:
            um = response.usage_metadata
            return LLMUsage(
                input_tokens=um.get("input_tokens", 0),
                output_tokens=um.get("output_tokens", 0),
                total_tokens=um.get("total_tokens", 0),
            )

        if hasattr(response, "response_metadata") and response.response_metadata:
            tu = response.response_metadata.get("token_usage", {})
            if tu:
                return LLMUsage(
                    input_tokens=tu.get("prompt_tokens", 0),
                    output_tokens=tu.get("completion_tokens", 0),
                    total_tokens=tu.get("total_tokens", 0),
                )

        return None

    def _map_exception(self, exc: Exception) -> LLMError:
        if isinstance(exc, LLMError):
            return exc

        if isinstance(exc, GroqAuthenticationError):
            return LLMAuthenticationError(str(exc), original_error=exc)
        if isinstance(exc, (GroqBadRequestError, GroqConfigurationError)):
            return LLMBadRequestError(str(exc), original_error=exc)
        if isinstance(exc, GroqStructuredOutputError):
            return LLMValidationError(str(exc), original_error=exc)
        if isinstance(exc, GroqRateLimitError):
            return LLMRateLimitError(str(exc), original_error=exc)
        if isinstance(exc, GroqTimeoutError):
            return LLMTimeoutError(str(exc), original_error=exc)
        if isinstance(exc, GroqAPIError):
            return LLMModelError(str(exc), original_error=exc)

        if isinstance(exc, (groq.AuthenticationError, groq.PermissionDeniedError)):
            return LLMAuthenticationError(f"Authentication failed: {exc}", original_error=exc)

        if isinstance(exc, (groq.BadRequestError, groq.UnprocessableEntityError)):
            return LLMBadRequestError(f"Bad request to LLM provider: {exc}", original_error=exc)
        if isinstance(exc, (ValidationError, OutputParserException)):
            return LLMValidationError(f"Structured output schema mismatch: {exc}", original_error=exc)

        if isinstance(exc, groq.RateLimitError):
            return LLMRateLimitError(f"Rate limit exceeded: {exc}", original_error=exc)

        if isinstance(exc, (groq.APITimeoutError, TimeoutError, asyncio.TimeoutError, httpx.TimeoutException)):
            return LLMTimeoutError(f"LLM request timed out: {exc}", original_error=exc)

        if isinstance(exc, (groq.InternalServerError, groq.APIConnectionError, httpx.NetworkError)):
            return LLMModelError(f"LLM server or connection failure: {exc}", original_error=exc)

        if isinstance(exc, groq.APIStatusError):
            status = getattr(exc, "status_code", None)
            if status in (401, 403):
                return LLMAuthenticationError(f"Authentication failed ({status}): {exc}", original_error=exc)
            if status in (400, 422):
                return LLMBadRequestError(f"Bad request ({status}): {exc}", original_error=exc)
            if status == 429:
                return LLMRateLimitError(f"Rate limit reached ({status}): {exc}", original_error=exc)
            if status and status >= 500:
                return LLMModelError(f"Upstream provider error ({status}): {exc}", original_error=exc)

        return LLMModelError(f"Unexpected LLM failure: {exc}", original_error=exc)

    async def generate(
        self,
        prompt: str,
        system_prompt: str | None = None,
        model: str | None = None,
        temperature: float | None = None,
        max_tokens: int | None = None,
        timeout: float | None = None,
    ) -> LLMResponse[str]:

        active_model = model or self.default_model
        active_timeout = timeout or self.default_timeout
        messages = self._build_messages(prompt=prompt, system_prompt=system_prompt)
        chat_model = self._get_chat_model(
            model=active_model,
            temperature=temperature,
            max_tokens=max_tokens,
            timeout=active_timeout,
        )

        logger.info(
            "Executing LLM generate: model=%s, prompt_len=%d, has_system_prompt=%s, timeout=%.1fs",
            active_model,
            len(prompt),
            bool(system_prompt),
            active_timeout,
        )

        start_time = time.perf_counter()

        retryer = AsyncRetrying(
            stop=stop_after_attempt(self.max_retries),
            wait=wait_random_exponential(min=1, max=8),
            retry=retry_if_exception_type((LLMRateLimitError, LLMTimeoutError, LLMModelError)),
            reraise=True,
            before_sleep=lambda state: logger.warning(
                "Transient error on LLM generate (attempt %d/%d). Retrying in %.2fs. Reason: %s",
                state.attempt_number,
                self.max_retries,
                state.next_action.sleep if state.next_action else 0.0,
                state.outcome.exception() if state.outcome else "Unknown",
            ),
        )

        try:
            async for attempt in retryer:
                with attempt:
                    try:
                        async with asyncio.timeout(active_timeout):
                            response = await chat_model.ainvoke(messages)
                    except Exception as raw_exc:
                        mapped_exc = self._map_exception(raw_exc)
                        raise mapped_exc from raw_exc

            latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
            content = str(response.content)
            usage = self._extract_usage(response)

            logger.info(
                "LLM generate completed: model=%s, latency=%.2fms, tokens=%s, status=SUCCESS",
                active_model,
                latency_ms,
                usage.total_tokens if usage else "unknown",
            )

            return LLMResponse[str](
                content=content,
                model=active_model,
                latency_ms=latency_ms,
                usage=usage,
            )

        except LLMError as err:
            latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
            logger.error(
                "LLM generate failed permanently: model=%s, latency=%.2fms, error_type=%s, message=%s",
                active_model,
                latency_ms,
                type(err).__name__,
                err,
            )
            raise

    async def generate_structured(
        self,
        prompt: str,
        response_model: type[TStruct],
        system_prompt: str | None = None,
        model: str | None = None,
        temperature: float | None = None,
        max_tokens: int | None = None,
        timeout: float | None = None,
    ) -> LLMResponse[TStruct]:

        active_model = model or self.default_model
        active_timeout = timeout or self.default_timeout
        messages = self._build_messages(prompt=prompt, system_prompt=system_prompt)

        struct_temp = temperature if temperature is not None else min(self.default_temperature, 0.2)

        try:
            if "_get_chat_model" in self.__dict__ or type(self)._get_chat_model is not LLMService._get_chat_model:
                chat_model = self._get_chat_model(
                    model=active_model,
                    temperature=struct_temp,
                    max_tokens=max_tokens,
                    timeout=active_timeout,
                )
                structured_runner = chat_model.with_structured_output(response_model, include_raw=True)
            else:
                structured_runner = groq_client.get_structured_model(
                    response_model,
                    model=active_model,
                    temperature=struct_temp,
                    max_tokens=max_tokens or self.default_max_tokens,
                    timeout=active_timeout,
                    max_retries=0,
                    include_raw=True,
                )
        except Exception as exc:
            raise self._map_exception(exc) from exc

        logger.info(
            "Executing LLM generate_structured: model=%s, schema=%s, prompt_len=%d, timeout=%.1fs",
            active_model,
            response_model.__name__,
            len(prompt),
            active_timeout,
        )

        start_time = time.perf_counter()

        retryer = AsyncRetrying(
            stop=stop_after_attempt(self.max_retries),
            wait=wait_random_exponential(min=1, max=8),
            retry=retry_if_exception_type((LLMRateLimitError, LLMTimeoutError, LLMModelError)),
            reraise=True,
            before_sleep=lambda state: logger.warning(
                "Transient error on structured LLM generate (attempt %d/%d). Retrying in %.2fs. Reason: %s",
                state.attempt_number,
                self.max_retries,
                state.next_action.sleep if state.next_action else 0.0,
                state.outcome.exception() if state.outcome else "Unknown",
            ),
        )

        try:
            async for attempt in retryer:
                with attempt:
                    try:
                        async with asyncio.timeout(active_timeout):
                            output = await structured_runner.ainvoke(messages)
                    except Exception as raw_exc:
                        mapped_exc = self._map_exception(raw_exc)
                        raise mapped_exc from raw_exc

            latency_ms = round((time.perf_counter() - start_time) * 1000, 2)

            if isinstance(output, dict):
                parsed_object = output.get("parsed")
                raw_message = output.get("raw")
                parsing_error = output.get("parsing_error")

                if parsing_error or parsed_object is None:
                    raise LLMValidationError(
                        f"Failed to parse LLM response into schema {response_model.__name__}: {parsing_error}"
                    )
                usage = self._extract_usage(raw_message)
            else:
                parsed_object = output
                usage = None

            logger.info(
                "LLM generate_structured completed: model=%s, schema=%s, latency=%.2fms, tokens=%s, status=SUCCESS",
                active_model,
                response_model.__name__,
                latency_ms,
                usage.total_tokens if usage else "unknown",
            )

            return LLMResponse[TStruct](
                content=cast(TStruct, parsed_object),
                model=active_model,
                latency_ms=latency_ms,
                usage=usage,
            )

        except LLMError as err:
            latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
            logger.error(
                "LLM generate_structured failed permanently: model=%s, schema=%s, latency=%.2fms, error_type=%s, message=%s",
                active_model,
                response_model.__name__,
                latency_ms,
                type(err).__name__,
                err,
            )
            raise


llm_service = LLMService()